-- Fase producto, punto 2: estados no lineales, entrevistas agendadas dentro del sistema e historial de cambios.

-- Dos estados nuevos: EN_PAUSA (se puede reanudar) y CANCELADO (terminal).
ALTER TABLE solicitudes DROP CONSTRAINT chk_solicitudes_estado;
ALTER TABLE solicitudes ADD CONSTRAINT chk_solicitudes_estado CHECK (estado IN (
    'PENDIENTE',
    'EN_PROCESO',
    'EN_PAUSA',
    'CANCELADO',
    'FINALIZADO'
));

-- Estado que tenia la solicitud antes de pausarse; al reanudar vuelve a ese estado.
ALTER TABLE solicitudes ADD COLUMN estado_previo VARCHAR(20);
ALTER TABLE solicitudes ADD CONSTRAINT chk_solicitudes_estado_previo CHECK (
    estado_previo IS NULL OR estado_previo IN ('PENDIENTE', 'EN_PROCESO')
);

-- Entrevistas que el evaluador agenda para una solicitud.
CREATE TABLE entrevistas (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id BIGINT                   NOT NULL REFERENCES solicitudes (id),
    inicio       TIMESTAMP WITH TIME ZONE NOT NULL,
    fin          TIMESTAMP WITH TIME ZONE NOT NULL,
    modalidad    VARCHAR(20)              NOT NULL,
    ubicacion    VARCHAR(300),
    estado       VARCHAR(20)              NOT NULL,
    CONSTRAINT chk_entrevistas_modalidad CHECK (modalidad IN ('ONLINE', 'PRESENCIAL')),
    CONSTRAINT chk_entrevistas_estado CHECK (estado IN ('AGENDADA', 'REALIZADA', 'CANCELADA')),
    CONSTRAINT chk_entrevistas_horario CHECK (fin > inicio)
);

CREATE INDEX idx_entrevistas_solicitud ON entrevistas (solicitud_id);
CREATE INDEX idx_entrevistas_inicio    ON entrevistas (inicio);
-- Una solicitud tiene como maximo una entrevista vigente; las realizadas y canceladas quedan como registro.
CREATE UNIQUE INDEX uq_entrevistas_agendada_por_solicitud ON entrevistas (solicitud_id) WHERE estado = 'AGENDADA';

-- Bitacora de la solicitud: quien hizo cada cambio, cuando y por que.
-- estado_anterior queda vacio en el registro de creacion; es igual a estado_nuevo cuando el cambio
-- no altera el estado (por ejemplo, reprogramar la entrevista o reasignar al evaluador).
CREATE TABLE historial_estados (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id    BIGINT                   NOT NULL REFERENCES solicitudes (id),
    usuario_id      BIGINT                   NOT NULL REFERENCES usuarios (id),
    estado_anterior VARCHAR(20),
    estado_nuevo    VARCHAR(20)              NOT NULL,
    comentario      VARCHAR(500),
    fecha           TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_historial_solicitud ON historial_estados (solicitud_id);
