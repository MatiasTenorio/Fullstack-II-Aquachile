CREATE TABLE solicitudes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    candidato_id    BIGINT       NOT NULL REFERENCES candidatos (id),
    cargo           VARCHAR(160) NOT NULL,
    familia_cargo   VARCHAR(60)  NOT NULL,
    fecha_solicitud DATE         NOT NULL,
    estado          VARCHAR(20)  NOT NULL,
    responsable_id  BIGINT       REFERENCES usuarios (id),
    observaciones   VARCHAR(2000),
    CONSTRAINT chk_solicitudes_estado CHECK (estado IN (
        'PENDIENTE',
        'EN_PROCESO',
        'FINALIZADO'
    ))
);

CREATE INDEX idx_solicitudes_candidato   ON solicitudes (candidato_id);
CREATE INDEX idx_solicitudes_responsable ON solicitudes (responsable_id);
CREATE INDEX idx_solicitudes_estado      ON solicitudes (estado);
