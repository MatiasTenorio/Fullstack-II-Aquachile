-- Fase producto, punto 5: cada evaluador conecta su propia cuenta de Google y sus entrevistas
-- se copian a su Google Calendar.

-- Id del evento en Google Calendar; vacio si la entrevista no se ha copiado a Google.
ALTER TABLE entrevistas ADD COLUMN google_event_id VARCHAR(255);

-- Cuenta de Google conectada por cada usuario (una por usuario).
CREATE TABLE google_conexiones (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id            BIGINT                   NOT NULL UNIQUE REFERENCES usuarios (id),
    google_email          VARCHAR(255),
    -- Permiso permanente que entrega Google; se guarda cifrado, nunca en claro
    refresh_token_cifrado TEXT                     NOT NULL,
    conectado_en          TIMESTAMP WITH TIME ZONE NOT NULL
);
