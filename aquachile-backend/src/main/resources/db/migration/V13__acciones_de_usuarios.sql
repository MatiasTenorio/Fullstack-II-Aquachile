-- Historial de acciones por usuario: cada accion que hace alguien en el sistema queda registrada
-- (quien, que, cuando y, en pausas y cancelaciones, el motivo). Lo consulta el administrador.

CREATE TABLE acciones_usuario (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id   BIGINT                   NOT NULL REFERENCES usuarios (id),
    tipo         VARCHAR(40)              NOT NULL,
    -- Texto completo de la accion, escrito al momento de hacerla (ej: "Pauso la solicitud #12 de Ana Perez")
    descripcion  VARCHAR(500)             NOT NULL,
    -- Motivo escrito por el usuario al pausar o cancelar una solicitud
    motivo       VARCHAR(500),
    solicitud_id BIGINT                   REFERENCES solicitudes (id),
    fecha        TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_acciones_usuario_fecha ON acciones_usuario (usuario_id, fecha DESC);

-- Carga las acciones que ya estaban en el historial de las solicitudes (desde la migracion V10),
-- para que el historial de cada usuario no parta vacio.
WITH previas AS (
    SELECT h.usuario_id,
           h.solicitud_id,
           h.fecha,
           h.comentario,
           '#' || s.id || ' de ' || c.nombre AS referencia,
           CASE
               WHEN h.estado_anterior IS NULL THEN 'SOLICITUD_CREADA'
               WHEN h.estado_nuevo = 'EN_PAUSA' AND h.estado_anterior <> 'EN_PAUSA' THEN 'SOLICITUD_PAUSADA'
               WHEN h.estado_nuevo = 'CANCELADO' AND h.estado_anterior <> 'CANCELADO' THEN 'SOLICITUD_CANCELADA'
               WHEN h.estado_nuevo = 'FINALIZADO' AND h.estado_anterior <> 'FINALIZADO' THEN 'SOLICITUD_FINALIZADA'
               WHEN h.estado_anterior = 'EN_PAUSA' AND h.estado_nuevo <> 'EN_PAUSA' THEN 'SOLICITUD_REANUADA'
               WHEN h.comentario LIKE 'Entrevista agendada%' THEN 'ENTREVISTA_AGENDADA'
               WHEN h.comentario LIKE 'Entrevista reprogramada%' THEN 'ENTREVISTA_REPROGRAMADA'
               WHEN h.comentario LIKE 'Entrevista realizada%' THEN 'ENTREVISTA_REALIZADA'
               WHEN h.comentario LIKE 'Asignada a%' THEN 'EVALUADOR_ASIGNADO'
               ELSE 'SOLICITUD_ACTUALIZADA'
           END AS tipo
    FROM historial_estados h
    JOIN solicitudes s ON s.id = h.solicitud_id
    JOIN candidatos c ON c.id = s.candidato_id
)
INSERT INTO acciones_usuario (usuario_id, tipo, descripcion, motivo, solicitud_id, fecha)
SELECT usuario_id,
       tipo,
       LEFT(CASE tipo
           WHEN 'SOLICITUD_CREADA' THEN 'Creó la solicitud ' || referencia || '. ' || COALESCE(comentario, '')
           WHEN 'SOLICITUD_PAUSADA' THEN 'Pausó la solicitud ' || referencia
           WHEN 'SOLICITUD_CANCELADA' THEN 'Canceló la solicitud ' || referencia
           WHEN 'SOLICITUD_FINALIZADA' THEN 'Finalizó la solicitud ' || referencia
           WHEN 'SOLICITUD_REANUADA' THEN 'Reanudó la solicitud ' || referencia
           ELSE COALESCE(comentario, 'Actualizó') || ' (solicitud ' || referencia || ')'
       END, 500),
       CASE WHEN tipo IN ('SOLICITUD_PAUSADA', 'SOLICITUD_CANCELADA') THEN comentario END,
       solicitud_id,
       fecha
FROM previas;
