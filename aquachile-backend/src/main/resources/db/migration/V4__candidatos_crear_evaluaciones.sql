CREATE TABLE evaluaciones (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitud_id          BIGINT NOT NULL UNIQUE REFERENCES solicitudes (id),
    fecha_evaluacion      DATE,
    resultado             VARCHAR(40),
    observaciones         VARCHAR(4000),
    informe_drive_file_id VARCHAR(255),
    CONSTRAINT chk_evaluaciones_resultado CHECK (resultado IS NULL OR resultado IN (
        'RECOMENDADO',
        'RECOMENDADO_CON_OBSERVACIONES',
        'NO_RECOMENDADO'
    ))
);
