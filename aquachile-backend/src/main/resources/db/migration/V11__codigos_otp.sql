-- Fase producto, punto 4: codigos de un solo uso (OTP) enviados por correo para definir o cambiar la contrasena.

CREATE TABLE codigos_otp (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- Usuario que recibe el codigo en su correo y debe ingresarlo
    usuario_id          BIGINT                   NOT NULL REFERENCES usuarios (id),
    proposito           VARCHAR(30)              NOT NULL,
    -- Solo en CAMBIO_POR_ADMIN: la cuenta a la que el administrador le cambiara la contrasena
    usuario_objetivo_id BIGINT                   REFERENCES usuarios (id),
    -- Nunca se guarda el codigo en claro, solo su hash
    codigo_hash         VARCHAR(255)             NOT NULL,
    creado_en           TIMESTAMP WITH TIME ZONE NOT NULL,
    expira_en           TIMESTAMP WITH TIME ZONE NOT NULL,
    intentos            INTEGER                  NOT NULL DEFAULT 0,
    usado               BOOLEAN                  NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_codigos_otp_proposito CHECK (proposito IN ('RESTABLECER_PASSWORD', 'CAMBIO_POR_ADMIN'))
);

CREATE INDEX idx_codigos_otp_usuario ON codigos_otp (usuario_id, proposito);
